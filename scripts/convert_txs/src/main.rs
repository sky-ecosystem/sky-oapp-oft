    #[test]
    fn test_hello_world_encoding() {
        let memo_program =
            Pubkey::from_str("MemoSq4gqABAXKb96qnH8TysNcWxMyWCqXgDLGmfcHr").unwrap();
        let payer =
            Pubkey::from_str("6Xu7SvWnBr1vo7Vst3cRZf2TW46PJxyZnNiv89RMMFuS").unwrap();
        let hardcoded = Pubkey::from_str(HARDCODED_CPI_ACCOUNT).unwrap();
        let data = "✩₊˚.⋆☾⋆⁺₊✧".as_bytes().to_vec();

        // Generated using: GOVERNANCE_ID=SKYGRikJcGSa3jC5HDyzDrVsmkCk3e5SqAurycny8PW cargo test -p governance --test msg_codec -- --exact --show-output test_msg_codec::test_hello_world
        let expected_target = "054a535a992921064d24e87160da387c7c35b5ddbc92bb81e41fa8404105448d";
        let expected_call_data = "0000e29ca9e2828acb9a2ee28b86e298bee28b86e281bae2828ae29ca7";

        // -- Actual: Solana Message -> serialize -> deserialize -> pipeline -------
        let solana_msg = Message::new(
            &[Instruction {
                program_id: memo_program,
                accounts: vec![],
                data: data,
            }],
            Some(&payer),
        );
        let wire = bincode::serialize(&solana_msg).unwrap();
        let deser: Message = bincode::deserialize(&wire).unwrap();

        let gov_msg = compiled_ix_to_governance_message(
            &deser,
            &deser.instructions[0],
            &hardcoded,
        );

        let mut actual_body = Vec::new();
        gov_msg.write_body(&mut actual_body).unwrap();
        let actual_target = hex::encode(gov_msg.program_id.to_bytes());
        let actual_call_data = hex::encode(&actual_body);

        // -- Assert exact match --------------------------------------------------
        assert_eq!(actual_target, expected_target, "dstTarget mismatch");
        assert_eq!(actual_call_data, expected_call_data, "dstCallData mismatch");
    }

    /// Verifies that HARDCODED_CPI_ACCOUNT is replaced with
    /// CPI_AUTHORITY_PLACEHOLDER and the resulting encoding matches
    /// a GovernanceMessage built with the placeholder directly.
    #[test]
    fn test_cpi_authority_replacement_encoding() {
        // Use an arbitrary program (not a builtin) so is_writable is not demoted.
        let program_id =
            Pubkey::from_str("627tpP7taNoCC2CvcV5qcftsVftpaeGiP78tyNEQoNLt").unwrap();
        let payer =
            Pubkey::from_str("6Xu7SvWnBr1vo7Vst3cRZf2TW46PJxyZnNiv89RMMFuS").unwrap();
        let hardcoded = Pubkey::from_str(HARDCODED_CPI_ACCOUNT).unwrap();
        let other_account =
            Pubkey::from_str("HC8D1rWMtAifPRhUYD7PwKHMtMVLtwCjarfNVvcN3SGK").unwrap();
        let data = vec![0xCA, 0xFE];

        // -- Build a Solana Message where hardcoded is a writable signer ----------
        let solana_msg = Message::new(
            &[Instruction {
                program_id,
                accounts: vec![
                    AccountMeta::new(hardcoded, true),       // signer + writable
                    AccountMeta::new(other_account, false),   // writable, not signer
                ],
                data: data.clone(),
            }],
            Some(&payer),
        );
        let wire = bincode::serialize(&solana_msg).unwrap();
        let deser: Message = bincode::deserialize(&wire).unwrap();

        let gov_msg = compiled_ix_to_governance_message(
            &deser,
            &deser.instructions[0],
            &hardcoded,
        );

        // -- The hardcoded account must now be CPI_AUTHORITY_PLACEHOLDER ----------
        assert_eq!(
            gov_msg.accounts[0].pubkey, CPI_AUTHORITY_PLACEHOLDER,
            "First account should be CPI_AUTHORITY_PLACEHOLDER"
        );
        assert!(gov_msg.accounts[0].is_signer);
        assert!(gov_msg.accounts[0].is_writable);

        // -- The other account must be unchanged ----------------------------------
        assert_eq!(gov_msg.accounts[1].pubkey, other_account);

        // -- Encoding must match a directly-built GovernanceMessage ----------------
        let expected = GovernanceMessage {
            origin_caller: [0u8; 32],
            program_id,
            accounts: vec![
                Acc { pubkey: CPI_AUTHORITY_PLACEHOLDER, is_signer: true, is_writable: true },
                Acc { pubkey: other_account, is_signer: false, is_writable: true },
            ],
            data: data,
        };

        let mut actual_body = Vec::new();
        gov_msg.write_body(&mut actual_body).unwrap();
        let mut expected_body = Vec::new();
        expected.write_body(&mut expected_body).unwrap();

        assert_eq!(
            hex::encode(gov_msg.program_id.to_bytes()),
            hex::encode(expected.program_id.to_bytes()),
            "dstTarget mismatch"
        );
        assert_eq!(
            hex::encode(&actual_body),
            hex::encode(&expected_body),
            "dstCallData mismatch"
        );
    }

    /// Mirror of test_spl_token_transfer from programs/governance/tests/msg_codec.rs.
    ///
    /// Builds an SPL Token TransferChecked instruction with the real CPI
    /// authority as the owner/signer, runs it through the pipeline (which
    /// replaces it with CPI_AUTHORITY_PLACEHOLDER), and asserts the encoded
    /// output is byte-identical to the governance test suite.
    #[test]
    fn test_spl_token_transfer_encoding() {
        // Generated using:
        // GOVERNANCE_ID=SKYGRikJcGSa3jC5HDyzDrVsmkCk3e5SqAurycny8PW cargo test -p governance --test msg_codec -- --exact --show-output test_msg_codec::test_spl_token_transfer
        let expected_target = "06ddf6e1d765a193d9cbe146ceeb79ac1cb485ed5f5b37913a8cf5857eff00a9";
        let expected_call_data = "0004\
            e1c50679ce41b750687dd3aba8c0542b2f24e8b3c1dfbb65e083a00894413ddf0001\
            f09487642c4d2af896c0a30072c237dfbec45c3c504e5cc0e00621f3b420b5bc0000\
            351d1961aca4539c1ac437655e391ecc2a57772e05d38d0aa012860cabc44ade0001\
            6370695f617574686f726974790000000000000000000000000000000000000001000c\
            0a0000000000000009";

        let hardcoded = Pubkey::from_str(HARDCODED_CPI_ACCOUNT).unwrap();
        let payer = Pubkey::from_str(DEFAULT_PAYER).unwrap();
        let spl_token_program =
            Pubkey::from_str("TokenkegQfeZyiNwAJbNbGKPFXCWuBvf9Ss623VQ5DA").unwrap();
        let mint =
            Pubkey::from_str("HC8D1rWMtAifPRhUYD7PwKHMtMVLtwCjarfNVvcN3SGK").unwrap();
        // Associated token address derived from the real CPI authority
        // (printed by the governance test: "Associated token address: GCJyy1ZQ...")
        let associated_token =
            Pubkey::from_str("GCJyy1ZQjDhRL7jpbJfxEKhcwv2Gxxv7ZpbxEfazGit6").unwrap();
        let destination =
            Pubkey::from_str("4aLLvFDsgPsz7WXWgAEVPXJ4Kpczbb2z8uPW4Aca2r1b").unwrap();

        // TransferChecked { amount: 10, decimals: 9 }.pack()
        let instruction_data = hex::decode("0c0a0000000000000009").unwrap();

        // Build Solana instruction with the real CPI authority as owner/signer.
        // The pipeline will replace it with CPI_AUTHORITY_PLACEHOLDER.
        let ix = Instruction {
            program_id: spl_token_program,
            accounts: vec![
                AccountMeta::new(associated_token, false),  // source ATA (writable)
                AccountMeta::new_readonly(mint, false),     // mint (readonly)
                AccountMeta::new(destination, false),       // destination (writable)
                AccountMeta::new_readonly(hardcoded, true), // owner (readonly signer)
            ],
            data: instruction_data,
        };

        let solana_msg = Message::new(&[ix], Some(&payer));
        let wire = bincode::serialize(&solana_msg).unwrap();
        let deser: Message = bincode::deserialize(&wire).unwrap();

        let gov_msg = compiled_ix_to_governance_message(
            &deser,
            &deser.instructions[0],
            &hardcoded,
        );

        // -- Verify the replacement happened correctly ----------------------------
        let owner_acc = gov_msg.accounts.iter().find(|a| a.pubkey == CPI_AUTHORITY_PLACEHOLDER);
        assert!(owner_acc.is_some(), "CPI_AUTHORITY_PLACEHOLDER not found in accounts");
        let owner_acc = owner_acc.unwrap();
        assert!(owner_acc.is_signer, "owner should be a signer");
        assert!(!owner_acc.is_writable, "owner should NOT be writable");

        // -- Assert exact match against governance test output --------------------
        let mut actual_body = Vec::new();
        gov_msg.write_body(&mut actual_body).unwrap();
        let actual_target = hex::encode(gov_msg.program_id.to_bytes());
        let actual_call_data = hex::encode(&actual_body);

        assert_eq!(actual_target, expected_target, "dstTarget mismatch");
        assert_eq!(actual_call_data, expected_call_data, "dstCallData mismatch");
    }
