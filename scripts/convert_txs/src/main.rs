// Converts Solana VersionedTransactions (from JSON) into GovernanceMessages.
//
// Usage:
//   cargo run -p convert-txs -- <txs.json>
//
// The JSON file should contain an array of objects with the format:
//   [{ "point": { "eid": u32, "address": "..." }, "data": "<hex>", "description": "..." }]
//
// For each Solana transaction (identified by point.eid), the tool:
//   1. Deserializes the hex data as a Solana legacy Message
//   2. Extracts each instruction
//   3. Replaces occurrences of HARDCODED_CPI_ACCOUNT with CPI_AUTHORITY_PLACEHOLDER
//   4. Builds and encodes a GovernanceMessage for each instruction
//
// origin_caller is NOT set here -- GovernanceOAppSender handles that on-chain.

use std::str::FromStr;

use base64::Engine;
use governance::msg_codec::{Acc, GovernanceMessage};
use governance::CPI_AUTHORITY_PLACEHOLDER;
use solana_sdk::instruction::{AccountMeta, Instruction};
use solana_sdk::message::Message;
use solana_sdk::pubkey::Pubkey;
use solana_sdk::transaction::Transaction;

/// The account address to replace with CPI_AUTHORITY_PLACEHOLDER in every instruction.
const HARDCODED_CPI_ACCOUNT: &str = "AYPtjx4Hc8us1ikULUedkmZ3wtiD6tmL7gK3qe4V3oHt";

/// Default payer used when building simulation transactions.
/// You can replace it with any address with SOL
const DEFAULT_PAYER: &str = "6Xu7SvWnBr1vo7Vst3cRZf2TW46PJxyZnNiv89RMMFuS";

#[derive(serde::Deserialize)]
struct TxEntry {
    point: Point,
    data: String,
    #[serde(default)]
    description: Option<String>,
}

#[derive(serde::Deserialize)]
struct Point {
    eid: u32,
    address: String,
}

fn main() {
    let args: Vec<String> = std::env::args().collect();

    if args.len() < 2 {
        eprintln!("Usage: {} <txs.json>", args[0]);
        eprintln!();
        eprintln!("Arguments:");
        eprintln!("  txs.json - JSON file containing Solana transactions generated by devtools");
        std::process::exit(1);
    }

    let file_path = &args[1];

    // -- Read & parse JSON ------------------------------------------------

    let json_data = std::fs::read_to_string(file_path).unwrap_or_else(|e| {
        eprintln!("Failed to read {}: {}", file_path, e);
        std::process::exit(1);
    });

    let entries: Vec<TxEntry> = serde_json::from_str(&json_data).unwrap_or_else(|e| {
        eprintln!("Failed to parse JSON: {}", e);
        std::process::exit(1);
    });

    // -- Resolve constants ------------------------------------------------

    let hardcoded_cpi_account = Pubkey::from_str(HARDCODED_CPI_ACCOUNT).expect("Invalid HARDCODED_CPI_ACCOUNT");
    let payer = Pubkey::from_str(DEFAULT_PAYER).expect("Invalid DEFAULT_PAYER");

    eprintln!("Hardcoded CPI account to replace : {}", HARDCODED_CPI_ACCOUNT);
    eprintln!("CPI_AUTHORITY_PLACEHOLDER         : {}", CPI_AUTHORITY_PLACEHOLDER);
    eprintln!();

    const SOLANA_EIDS: &[u32] = &[30168, 40168];

    for (i, entry) in entries.iter().enumerate() {
        // Only process Solana transactions (identified by point.eid)
        if !SOLANA_EIDS.contains(&entry.point.eid) {
            eprintln!("Skipping entry #{} (eid {} is not a Solana eid)", i, entry.point.eid);
            continue;
        }

        let desc = entry
            .description
            .as_deref()
            .unwrap_or("(no description)");
        println!("=== Entry #{}: {} ===", i, desc);
        println!(
            "  Point: eid={}, address={}",
            entry.point.eid, entry.point.address
        );

        let msg_bytes = match hex::decode(&entry.data) {
            Ok(b) => b,
            Err(e) => {
                eprintln!("  Failed to decode hex for entry #{}: {}", i, e);
                continue;
            }
        };

        if msg_bytes.is_empty() {
            eprintln!("  Empty data, skipping");
            continue;
        }

        // Check the version byte – high bit set means V0/versioned message
        if msg_bytes[0] & 0x80 != 0 {
            eprintln!("  Skipping: V0/versioned messages are not yet supported");
            continue;
        }

        // Deserialize as a legacy Solana Message (wire format == bincode with short_vec)
        let message: Message = match bincode::deserialize(&msg_bytes) {
            Ok(m) => m,
            Err(e) => {
                eprintln!("  Failed to deserialize Message for entry #{}: {}", i, e);
                continue;
            }
        };

        let account_keys = &message.account_keys;

        eprintln!("  Account keys ({}):", account_keys.len());
        for (k, key) in account_keys.iter().enumerate() {
            let marker = if *key == hardcoded_cpi_account {
                " <-- HARDCODED_CPI_ACCOUNT (will be replaced)"
            } else {
                ""
            };
            eprintln!("    [{}] {}{}", k, key, marker);
        }
        eprintln!();

        // -- Extract instructions and build GovernanceMessages ----------------

        for (j, ix) in message.instructions.iter().enumerate() {
            let gov_msg = compiled_ix_to_governance_message(
                &message,
                ix,
                &hardcoded_cpi_account,
            );

            println!("  --- Instruction #{} ---", j);
            println!("  Program: {}", gov_msg.program_id);

            for (k, acc) in gov_msg.accounts.iter().enumerate() {
                let marker = if acc.pubkey == CPI_AUTHORITY_PLACEHOLDER {
                    " [CPI_AUTHORITY_PLACEHOLDER]"
                } else {
                    ""
                };
                println!(
                    "    Account[{}]: {} (signer={}, writable={}){}",
                    k, acc.pubkey, acc.is_signer, acc.is_writable, marker
                );
            }

            println!("  Instruction data (hex): {}", hex::encode(&gov_msg.data));

            // -- Encode GovernanceMessage body (for EVM governance call) -------

            let mut body_buf = Vec::new();
            gov_msg.write_body(&mut body_buf).unwrap();
            println!();
            println!("  dstTarget   : {}", hex::encode(gov_msg.program_id.to_bytes()));
            println!("  dstCallData : {}", hex::encode(&body_buf));

            // -- Simulation transaction ----------------------------------------
            // Replace CPI_AUTHORITY_PLACEHOLDER back with the original account
            // so the transaction can be simulated on-chain.

            let sim_tx = Transaction::new_with_payer(
                &[Instruction {
                    program_id: gov_msg.program_id,
                    accounts: gov_msg
                        .accounts
                        .iter()
                        .map(|a| AccountMeta {
                            pubkey: if a.pubkey == CPI_AUTHORITY_PLACEHOLDER {
                                hardcoded_cpi_account
                            } else {
                                a.pubkey
                            },
                            is_signer: a.is_signer,
                            is_writable: a.is_writable,
                        })
                        .collect(),
                    data: gov_msg.data.clone(),
                }],
                Some(&payer),
            );

            println!(
                "  Simulation (base64): {}",
                base64::engine::general_purpose::STANDARD.encode(sim_tx.message_data())
            );
            println!();
        }

        println!();
    }
}
