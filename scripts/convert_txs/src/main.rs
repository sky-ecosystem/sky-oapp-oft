// Core conversion logic (extracted for testability)
// ---------------------------------------------------------------------------

/// Convert a single compiled instruction (from a deserialized Solana Message)
/// into a GovernanceMessage, replacing `replace_pubkey` with CPI_AUTHORITY_PLACEHOLDER.
fn compiled_ix_to_governance_message(
    message: &Message,
    ix: &solana_sdk::instruction::CompiledInstruction,
    replace_pubkey: &Pubkey,
) -> GovernanceMessage {
    let account_keys = &message.account_keys;
    let program_id = account_keys[ix.program_id_index as usize];

    let accounts: Vec<Acc> = ix
        .accounts
        .iter()
        .map(|&idx| {
            let idx = idx as usize;
            let pubkey = account_keys[idx];
            let replaced = pubkey == *replace_pubkey;
            Acc {
                pubkey: if replaced {
                    CPI_AUTHORITY_PLACEHOLDER
                } else {
                    pubkey
                },
                is_signer: message.is_signer(idx),
                is_writable: message.is_writable(idx),
            }
        })
        .collect();

    GovernanceMessage {
        origin_caller: [0u8; 32], // set by GovernanceOAppSender on-chain
        program_id,
        accounts,
        data: ix.data.clone(),
    }
}

